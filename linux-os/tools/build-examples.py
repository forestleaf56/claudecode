#!/usr/bin/env python3
"""Bundle linux-os/examples/** into js/code-examples.js (OS.codeExamples = {path: source})."""
import json, os
root = os.path.join(os.path.dirname(__file__), '..', 'examples')
files = {}
for d, _, names in os.walk(root):
    for n in sorted(names):
        p = os.path.join(d, n)
        files[os.path.relpath(p, root).replace(os.sep, '/')] = open(p, encoding='utf-8').read()
out = os.path.join(os.path.dirname(__file__), '..', 'js', 'code-examples.js')
with open(out, 'w', encoding='utf-8') as f:
    f.write('/* Cirrus Linux — Nimbus Code example programs (generated by tools/build-examples.py from examples/) */\n')
    f.write('OS.codeExamples = ' + json.dumps(dict(sorted(files.items())), ensure_ascii=False, indent=0).replace('</script', '<\\/script') + ';\n')
print(len(files), 'examples ->', os.path.relpath(out))
